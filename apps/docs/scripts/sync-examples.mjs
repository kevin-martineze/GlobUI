// Writes examples/registry.ts from the files in examples/. Run before dev and build.
// An example is any examples/<group>/<name>.tsx file; the registry key is "<group>/<name>".
import { readdirSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "examples")

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = path.join(dir, entry)
    if (statSync(full).isDirectory()) return walk(full)
    return entry.endsWith(".tsx") && full !== path.join(root, "registry.tsx") ? [full] : []
  })
}

const examples = walk(root)
  .map((file) => path.relative(root, file).replace(/\.tsx$/, "").split(path.sep).join("/"))
  .sort()

const identifier = (name) =>
  name
    .split(/[/-]/)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("") + "Example"

const imports = examples.map((name) => `import ${identifier(name)} from "./${name}"`).join("\n")
const entries = examples.map((name) => `  "${name}": ${identifier(name)},`).join("\n")

writeFileSync(
  path.join(root, "registry.ts"),
  `// Generated by scripts/sync-examples.mjs. Do not edit by hand.
import type { ComponentType } from "react"
${imports}

export const registry: Record<string, ComponentType> = {
${entries}
}
`
)
console.log(`examples registry: ${examples.length} examples`)
