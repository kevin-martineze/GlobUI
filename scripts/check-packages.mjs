// Validates every publishable @glob-ui/* package: publint and @arethetypeswrong (attw) on the
// packed tarball, plus the release metadata. Run after `pnpm build:packages`.
// Exits 1 on any problem. There are no exceptions: a rule that cannot pass needs a written reason here.
import { spawnSync } from "node:child_process"
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs"
import os from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const packagesDir = path.join(root, "packages")
const license = readFileSync(path.join(root, "LICENSE"), "utf8")
const problems = []
const checked = []
// Kept off npm on purpose: work on Vue and Angular is paused, and they have only the layouts and Sheet (see
// RELEASING.md). They are still checked, so they are ready when they are made public. Remove a package from this
// list when it is made public; a listed package that is not private fails, so the list stays current.
const heldBack = new Set(["@glob-ui/vue", "@glob-ui/angular"])

for (const dir of readdirSync(packagesDir)) {
  const pkgDir = path.join(packagesDir, dir)
  const manifestPath = path.join(pkgDir, "package.json")
  if (!existsSync(manifestPath)) continue
  const pkg = JSON.parse(readFileSync(manifestPath, "utf8"))
  const label = pkg.name
  checked.push(label)

  // Release metadata.
  if (heldBack.has(label)) {
    if (!pkg.private) problems.push(`${label}: public, so remove it from heldBack`)
  } else if (pkg.private) problems.push(`${label}: still private`)
  if (pkg.license !== "MIT") problems.push(`${label}: license must be MIT`)
  if (pkg.publishConfig?.access !== "public") problems.push(`${label}: publishConfig.access must be public`)
  if (pkg.publishConfig?.provenance !== true) problems.push(`${label}: publishConfig.provenance must be true`)
  if (!pkg.repository?.url?.includes("kevin-martineze/GlobUI")) problems.push(`${label}: repository.url missing`)
  if (!pkg.description) problems.push(`${label}: description missing`)
  // Angular's publish manifest is generated by ng-packagr inside dist/. The exports map, sideEffects and the files of the
  // package are checked on the packed manifest instead (see the angular branch below). The root manifest has no
  // exports or files on purpose, so these rules skip Angular here.
  if (dir !== "angular" && !pkg.exports?.["./package.json"]) problems.push(`${label}: exports must include ./package.json`)
  if (pkg.sideEffects === undefined && dir !== "angular") problems.push(`${label}: sideEffects missing`)
  if (dir !== "angular" && (!pkg.files?.includes("LICENSE") || !pkg.files?.includes("README.md"))) problems.push(`${label}: files must include LICENSE and README.md`)
  const copy = path.join(pkgDir, "LICENSE")
  if (!existsSync(copy) || readFileSync(copy, "utf8") !== license) problems.push(`${label}: LICENSE copy missing or out of date (run pnpm sync:packages)`)
  if (!existsSync(path.join(pkgDir, "README.md"))) problems.push(`${label}: README.md missing (run pnpm sync:packages)`)

  // Built output and tarball rules, for packages with JavaScript.
  if (dir === "angular") {
    // Angular publishes its APF output: publishConfig.directory is dist/, so pnpm pack (run in the package) packs dist/
    // with the workspace versions rewritten. The rules run on that tarball, the artifact that is published.
    const packDir = mkdtempSync(path.join(os.tmpdir(), "glob-ui-angular-pack-"))
    try {
      const pack = spawnSync("pnpm", ["pack", "--pack-destination", packDir], { cwd: pkgDir, encoding: "utf8" })
      if (pack.status !== 0) {
        problems.push(`${label}: pnpm pack\n${pack.stdout}${pack.stderr}`)
      } else {
        const tgz = readdirSync(packDir).find((file) => file.endsWith(".tgz"))
        const tarball = path.join(packDir, tgz)
        const extract = spawnSync("tar", ["-xzf", tarball, "-C", packDir], { encoding: "utf8" })
        if (extract.status !== 0) problems.push(`${label}: extract\n${extract.stderr}`)
        const packed = path.join(packDir, "package")
        for (const file of ["LICENSE", "README.md", "package.json"]) {
          if (!existsSync(path.join(packed, file))) problems.push(`${label}: the tarball has no ${file}`)
        }
        const packedManifest = JSON.parse(readFileSync(path.join(packed, "package.json"), "utf8"))
        if (readFileSync(path.join(packed, "package.json"), "utf8").includes("workspace:")) {
          problems.push(`${label}: the packed package.json still has workspace: versions`)
        }
        if (!packedManifest.exports?.["./package.json"]) problems.push(`${label}: the packed exports must include ./package.json`)
        if (packedManifest.sideEffects === undefined) problems.push(`${label}: the packed sideEffects is missing`)
        const publint = spawnSync("pnpm", ["exec", "publint", packed, "--strict"], { cwd: root, encoding: "utf8" })
        if (publint.status !== 0) problems.push(`${label}: publint\n${publint.stdout}${publint.stderr}`)
        // Angular is ESM-only by design (no CJS build). The esm-only profile reports the CJS and node10 findings as
        // ignored; every other problem still fails. This is a real check, not a skip.
        const attw = spawnSync("pnpm", ["exec", "attw", tarball, "--profile", "esm-only"], { cwd: root, encoding: "utf8" })
        const out = (attw.stdout ?? "") + (attw.stderr ?? "")
        if (attw.status !== 0) problems.push(`${label}: attw (esm-only)\n${out}`)
      }
    } finally {
      rmSync(packDir, { recursive: true, force: true })
    }
  } else if (existsSync(path.join(pkgDir, "dist"))) {
    const publint = spawnSync("pnpm", ["exec", "publint", pkgDir, "--strict"], { cwd: root, encoding: "utf8" })
    if (publint.status !== 0) problems.push(`${label}: publint\n${publint.stdout}${publint.stderr}`)

    // attw cannot evaluate the ".svelte" entry points, so the Svelte package is skipped for it (publint still runs).
    if (dir !== "svelte") {
      const attw = spawnSync("pnpm", ["exec", "attw", "--pack", pkgDir], { cwd: root, encoding: "utf8" })
      const out = (attw.stdout ?? "") + (attw.stderr ?? "")
      if (attw.status !== 0 || !out.includes("No problems found")) problems.push(`${label}: attw\n${out}`)
    }
  }
}

console.log(`checked ${checked.length} packages: ${checked.join(", ")}`)
if (problems.length) {
  console.error("Package check failed:\n" + problems.map((p) => "  - " + p).join("\n"))
  process.exit(1)
}
console.log("Package check OK (publint --strict, attw, metadata).")
